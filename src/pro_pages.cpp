void Pages::info(){
    hyperlink(HTML_HOMEPAGE_URL, (const char*)HTML_MODEL);
    add("\r\n<br>Device name: ");
    add(HTML_DEV_NAME);
    
    if (extsett->apEN == 0){
        add("\r\n<br>AP: Disable");
    } else {
        add("\r\n<br>AP: ");
        add(extsett->ap_ssid); add(", "); add(ip4(extsett->apIP));
    }

    add("\r\n<br>Wi-Fi: ");
    if (extsett->staEN == 0){
        add("Not active");
    } else {
        if (extsett->staDHCP == 0){
            add(extsett->sta_ssid);
            add(", "); add(ip4(extsett->staIP));
        } else {
            add(extsett->sta_ssid);
            add(", "); add(ip4(extsett->staDHCP_IP));
        }
    }

    add(HTML_BR);
    link_button(HTML_GITHUB_URL, "Github repo");
}

