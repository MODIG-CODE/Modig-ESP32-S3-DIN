void Pages::ena_dis(const char* id, const char* label, uint8_t val){
	add("<label for=\""); add(id);
    add("\">"); add(label); 
    add("</label>\r\n");
	add("<br><select name=\""); add(id); add("\" id=\""); add(id); add("\">\r\n");
    if (val == 0){
	    add("<option value=\"0\" hidden>DISABLE</option>\r\n"); 
    } else {
	    add("<option value=\"1\" hidden>ENABLE</option>\r\n"); 
    }
	add("<option value=\"0\">DISABLE</option>\r\n");
	add("<option value=\"1\">ENABLE</option>\r\n");
	add("</select>\r\n");
}


